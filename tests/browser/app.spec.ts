import { expect, test } from '@playwright/test'

test('Relic is a tradable archived case, separate from POA, with accessible modal controls', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('.campaign-card')).toHaveCount(7)
  await page.locator('.case-spotlight').click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByRole('heading', { name: 'Relic Genesis 铸造' })).toBeVisible()
  await expect(dialog.getByText('历史首枚 1 USDT', { exact: true })).toBeVisible()
  await expect(dialog.getByText('已归档', { exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(page.locator('.case-spotlight')).toBeFocused()
})

test('combined filters, empty state, reset, and slash search work', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('textbox', { name: '搜索活动' })).toBeVisible()
  await page.keyboard.press('/')
  await expect(page.getByRole('textbox', { name: '搜索活动' })).toBeFocused()
  await page.getByRole('textbox', { name: '搜索活动' }).fill('Ptah')
  await expect(page.locator('.campaign-card')).toHaveCount(2)
  await page.getByLabel('仅进行中').check()
  await expect(page.locator('.campaign-card')).toHaveCount(1)
  await page.getByLabel('筛选网络').selectOption('X Layer / BNB')
  await expect(page.getByText('暂时没有匹配的活动')).toBeVisible()
  await page.getByRole('button', { name: '重置筛选' }).click()
  await expect(page.locator('.campaign-card')).toHaveCount(7)
})

test('bookmarks and participation checklist survive reload', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '收藏 Proof of Agent', exact: true }).click()
  await page.reload()
  await page.getByRole('button', { name: '我的收藏' }).click()
  await expect(page.locator('.campaign-card')).toHaveCount(1)
  await page.getByRole('button', { name: '查看详情' }).click()
  await page.getByRole('dialog').getByRole('checkbox').first().check()
  await page.keyboard.press('Escape')
  await page.reload()
  await page.getByRole('button', { name: 'Proof of Agent', exact: true }).click()
  await expect(page.getByRole('dialog').getByRole('checkbox').first()).toBeChecked()
})

test('calculator shows UNKNOWN until a value is supplied; sample is explicitly hypothetical', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '收益计算器' }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByText('UNKNOWN', { exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: '填入一个演算示例' }).click()
  await expect(dialog.getByText('+$5.12', { exact: true })).toBeVisible()
  await dialog.getByLabel('获奖概率假设').fill('0')
  await expect(dialog.locator('.net-result')).toContainText('−$0.88')
})

test('submission stores a draft and accurately says it was not sent', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '提交活动', exact: true }).click()
  await page.getByLabel('活动名称').fill('测试活动')
  await page.getByLabel('原始规则链接').fill('https://example.com/campaign')
  await page.getByRole('button', { name: '保存本地线索' }).click()
  await expect(page.getByText('好线索，已记下。')).toBeVisible()
  await expect(page.getByText(/尚未发送给网站运营者/)).toBeVisible()
  const drafts = await page.evaluate(() => JSON.parse(localStorage.getItem('glean-submissions-v1') || '[]'))
  expect(drafts[0].name).toBe('测试活动')
})

